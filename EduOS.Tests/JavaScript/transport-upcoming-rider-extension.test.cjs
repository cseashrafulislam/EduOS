const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
test('upcoming rider extension is wired end-to-end and protects existing terms', () => {
    const service = read('EduOS.Service/Services/Transport/TransportService.UpcomingRiderExtension.cs');
    const iface = read('EduOS.Core/Interfaces/IServices/ITransportService.cs');
    const api = read('EduOS.App/Controllers/Api/TransportController.cs');
    const view = read('EduOS.App/Views/TransportOperations/Index.cshtml');
    const index = read('EduOS.App/wwwroot/js/transport-operations/index.js');
    const js = read('EduOS.App/wwwroot/js/transport-operations/upcoming-rider-extension.js');
    assert.match(iface, /ExtendUpcomingRiderAsync/);
    assert.match(api, /HttpPost\("assignments\/\{reference:guid\}\/extend-upcoming"\)/);
    assert.match(api, /Authorize\(Roles = "TenantAdmin,Principal,TransportManager"\)/);
    assert.match(service, /IsolationLevel\.Serializable/);
    assert.match(service, /CanManageCampusAsync/);
    assert.match(service, /RowVersion\.AsSpan\(\)\.SequenceEqual/);
    assert.match(service, /PeakReservedSeats/);
    assert.match(service, /x\.StudentId == assignment\.StudentId/);
    assert.match(service, /x\.EffectiveTo\.Value >= request\.EndDate/);
    assert.match(service, /assignment\.UpdatedBy = _currentUser\.UserId/);
    assert.match(view, /transportUpcomingRiderExtensionPanel/);
    assert.match(view, /upcoming-rider-extension\.js/);
    assert.match(index, /transport:extend-upcoming-rider/);
    assert.match(js, /rowVersion: pending\.rowVersion/);
    assert.doesNotMatch(js, /innerHTML/);
});
