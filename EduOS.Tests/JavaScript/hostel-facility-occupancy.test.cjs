'use strict';
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const root = path.resolve(__dirname, '../..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const service = read('EduOS.Service/Services/Hostel/HostelService.Facilities.cs');
const dto = read('EduOS.Core/DTOs/Hostel/HostelFacilityDtos.cs');
const view = read('EduOS.App/Views/HostelOperations/Index.cshtml');
const js = read('EduOS.App/wwwroot/js/hostel-operations/facilities.js');
assert.match(dto, /public int ActiveReservations \{ get; set; \}/);
const list = service.slice(service.indexOf('GetFacilitiesAsync('), service.indexOf('CreateFacilityAsync('));
const state = service.slice(service.indexOf('SetFacilityStateAsync('));
assert.match(list, /var today = DateOnly.FromDateTime\(_clock.GetLocalNow\(\).DateTime\)/);
assert.match(list, /allocation.StartDate <= today && \(!allocation.EndDate.HasValue \|\| allocation.EndDate.Value >= today\)/);
assert.match(list, /ActiveReservations = activeReservations.GetValueOrDefault\(x.Id\)/);
assert.match(list, /OccupiedBeds = occupiedBeds.GetValueOrDefault\(x.Id\)/);
assert.match(state, /OccupiedBeds = occupiedToday, ActiveReservations = activeReservations/);
assert.match(state, /!request.IsActive && \(activeRooms > 0 \|\| activeReservations > 0\)/);
assert.match(state, /IsolationLevel.Serializable/);
assert.match(list, /hostel.TenantId == tenant && campus.TenantId == tenant/);
assert.match(view, /<th>Occupied today<\/th><th>Active reservations<\/th>/);
assert.match(js, /item.occupiedBeds,\s*item.activeReservations/);
assert.match(js, /item.activeRooms > 0 \|\| item.activeReservations > 0/);
assert.match(js, /cell.colSpan = 8/);
assert.doesNotMatch(js, /innerHTML/);
new Function(js);
console.log('Hostel facility occupancy contracts and JS syntax: PASS');
