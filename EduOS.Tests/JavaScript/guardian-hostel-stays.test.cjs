const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const service = read('EduOS.Service/Services/Hostel/GuardianHostelStayService.cs');
const api = read('EduOS.App/Controllers/Api/GuardianHostelStaysController.cs');
const print = read('EduOS.App/Controllers/GuardianHostelStaysPrintController.cs');
const view = read('EduOS.App/Views/HostelOperations/Index.cshtml');
const js = read('EduOS.App/wwwroot/js/hostel-operations/guardian-stays.js');
assert.match(service, /link\.IsAuthorizedPickup/);
assert.match(service, /guardian\.UserId == user\.UserId/);
assert.match(service, /enrollment\.CampusId == campus\.Id/);
assert.match(service, /stay\.State == HostelAllocationState\.Active/);
assert.match(service, /pageSize is < 1 or > 20/);
assert.match(api, /Authorize\(Roles = "Guardian,Parent"\)/);
assert.match(api, /RequireModule\("HOSTEL"\)/);
assert.match(print, /RequireModule\("HOSTEL"\)/);
assert.match(view, /hostelGuardianStays/);
assert.match(js, /guardian-stays\/export/);
assert.doesNotMatch(service, /MonthlyRent|SecurityDeposit|FeeHeadId/);
