const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');

test('sign-in activity uses canonical login history with account and tenant isolation', () => {
    const model = read('EduOS.Core/Entities/Auth/AuthEntities.cs');
    const dto = read('EduOS.Core/DTOs/Auth/AuthDtos.cs');
    const service = read('EduOS.Service/Services/Auth/LoginActivityService.cs');
    const api = read('EduOS.App/Controllers/Api/LoginActivityApiController.cs');
    const mvc = read('EduOS.App/Controllers/LoginActivityController.cs');
    const view = read('EduOS.App/Views/LoginActivity/Index.cshtml');
    const js = read('EduOS.App/wwwroot/js/account/login-activity.js');
    const di = read('EduOS.App/Extensions/ApplicationServiceExtensions.cs');
    const nav = read('EduOS.App/Views/Shared/_Layout.cshtml');
    assert.match(model, /class LoginHistory : BaseEntity/);
    assert.match(dto, /class LoginHistoryDto/);
    assert.match(service, /x\.UserId == user\.UserId/);
    assert.match(service, /x\.TenantId == user\.TenantId/);
    assert.match(service, /x\.TenantId == null/);
    assert.match(api, /CurrentSessionValidAsync\(\)/);
    assert.match(api, /AuthSessionRegistry\.IsValidAsync\(db, userId, sid, tenantId\)/);
    assert.match(view, /loginActivityScope/);
    assert.match(js, /result\.set\('unassigned', 'true'\)/);
    assert.match(service, /DateTime\.SpecifyKind\(item\.OccurredAt, DateTimeKind\.Utc\)/);
    assert.match(service, /pageSize is < 1 or > 50/);
    assert.doesNotMatch(service, /IgnoreQueryFilters\(/);
    assert.doesNotMatch(service, /IpAddress =|UserAgent =|FailureReason =/);
    assert.match(api, /\[Authorize\]/);
    assert.match(api, /AutoValidateAntiforgeryToken/);
    assert.match(mvc, /\[Authorize\]/);
    assert.match(di, /AddScoped<ILoginActivityService, LoginActivityService>/);
    assert.match(nav, /href="\/LoginActivity\/Index"/);
    assert.match(view, /login-activity\.js/);
    assert.match(view, /LoginActivityHelpText/);
    assert.match(view, /loginActivityExport/);
    assert.match(view, /loginActivityFrom/);
    assert.match(js, /credentials: 'same-origin'/);
    assert.match(js, /cell\.textContent/);
    assert.doesNotMatch(js, /innerHTML/);
});


test('sign-in activity pins screen and CSV downloads to the original institution session', () => {
    const js = read('EduOS.App/wwwroot/js/account/login-activity.js');
    const view = read('EduOS.App/Views/LoginActivity/Index.cshtml');
    const auth = read('EduOS.App/Controllers/Api/AuthController.cs');
    assert.match(view, /data-session-error="@T\["LoginActivitySessionChanged"\]"/);
    assert.match(js, /document\.body\?\.dataset\.authSessionReference/);
    assert.match(js, /fetch\('\/api\/auth\/session-context'/);
    assert.match(js, /body\.data\?\.sessionReference !== originalSession/);
    assert.match(js, /window\.EduOSNotifySessionChanged\?\.\(\)/);
    assert.match(js, /await assertSessionUnchanged\(\);/);
    assert.equal((js.match(/await assertSessionUnchanged\(\);/g) || []).length, 3);
    assert.match(auth, /SaveLoginHistoryAsync\(user, ip, userAgent, true, null, session\.TenantId\)/);
    assert.match(auth, /member\.TenantId == requestedTenantId\.Value/);
    assert.match(auth, /member\.Status == MembershipStatus\.Active/);
    assert.match(auth, /tenant\.State == TenantState\.Active/);
});
