'use strict';
// Fast source-level UX B contracts only. These checks are NOT browser, SQL or security Final QA.
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const ledger = read('docs/ux/lanes/UX_B.md');
const routes = [...ledger.matchAll(/^- \[[ x]\] \x60(\/[^\x60]+)\x60/gm)].map(match => match[1]);
const viewFor = route => {
    if (route === '/offline-study.html') return 'EduOS.App/wwwroot/offline-study.html';
    const clean = route.split('#')[0];
    const [controller, action] = clean.split('/').filter(Boolean);
    if (controller === 'Admissions') {
        if (['Forms', 'NewApplication', 'Applications'].includes(action))
            return 'EduOS.App/Views/Admissions/Index.cshtml';
        if (['AssessmentSetup', 'Merit'].includes(action))
            return 'EduOS.App/Views/Admissions/Assessments.cshtml';
    }
    if (controller === 'Attendance') return 'EduOS.App/Views/Attendance/Index.cshtml';
    return 'EduOS.App/Views/' + controller + '/' + action + '.cshtml';
};
const views = () => [...new Set(routes.map(viewFor))];
test('UX B owns exactly 42 unique sidebar routes backed by canonical views', () => {
    assert.equal(routes.length, 42);
    assert.equal(new Set(routes).size, 42);
    for (const route of routes) {
        const view = viewFor(route);
        assert.ok(fs.existsSync(path.join(root, view)), route + ': missing ' + view);
    }
});
test('UX B pages retain shell titles and do not render duplicate h1 headings', () => {
    for (const file of views()) {
        const content = read(file);
        if (file.endsWith('/offline-study.html')) {
            assert.match(content, /<title>/i);
            assert.match(content, /How to use/);
            continue;
        }
        assert.match(content, /ViewData\["Title"\]/, file);
        assert.doesNotMatch(content, /<h1\b/i, file + ': duplicates shell h1');
        assert.doesNotMatch(content, /<th\s+scope="col"ead>/i, file);
        assert.equal((content.match(/<thead(?:\s[^>]*)?>/g) || []).length,
            (content.match(/<\/thead>/g) || []).length, file + ': unbalanced table headers');
    }
});
test('local page JS assets referenced by UX B views exist', () => {
    for (const file of views()) {
        const content = read(file);
        for (const match of content.matchAll(/<script[^>]*src=["']~\/([^"']+\.js)["']/g)) {
            const script = path.join(root, 'EduOS.App/wwwroot', match[1]);
            assert.ok(fs.existsSync(script), file + ': missing script ' + match[1]);
        }
    }
});
test('each UX B app route has reviewed bilingual contextual help', () => {
    const source = read('EduOS.App/wwwroot/js/platform/page-context-help.js').toLowerCase();
    for (const route of routes.filter(x => x !== '/offline-study.html')) {
        const p = route.split('#')[0].toLowerCase();
        const key = p.endsWith('/index') ? p : p + '/index';
        assert.ok(source.includes("'" + key + "':") || source.includes('"' + key + '":'),
            'No route-specific Page Help for ' + route);
    }
});
test('internal admission, category and branch codes are generated by server rather than entered', () => {
    const admission = read('EduOS.App/Views/Admissions/Index.cshtml');
    const category = read('EduOS.App/Views/Library/Index.cshtml');
    const branch = read('EduOS.App/Views/Library/Branches.cshtml');
    for (const [source, id] of [[admission, 'intakeCode'], [category, 'categoryCode'], [branch, 'branchCode']])
        assert.match(source, new RegExp('id="' + id + '" type="hidden"'));
    assert.match(read('EduOS.Service/Services/Admission/AdmissionIntakeService.cs'), /"ADM-" \+ request\.ClientRequestId/);
    assert.match(read('EduOS.Service/Services/Library/LibraryService.cs'), /"CAT-" \+ \(request\.ClientRequestId/);
    assert.match(read('EduOS.Service/Services/Library/LibraryBranchService.Write.cs'), /"BR-" \+ \(request\.ClientRequestId/);
    assert.match(read('EduOS.Core/DTOs/Library/LibraryBranchDtos.cs'), /ClientRequestId/);
    assert.match(read('EduOS.Core/DTOs/Library/LibraryDtos.cs'), /ClientRequestId/);
});
test('admission and library controllers retain module and authorization boundaries', () => {
    const adm = read('EduOS.App/Controllers/AdmissionsController.cs');
    const lib = read('EduOS.App/Controllers/LibraryController.cs');
    assert.match(adm, /RequireModule\("ADMISSION"\)/);
    assert.match(adm, /Authorize\(Roles = "TenantAdmin,AdmissionOfficer"\)/);
    assert.match(lib, /RequireModule\("LIBRARY"\)/);
    assert.match(lib, /Authorize/);
    assert.match(read('EduOS.App/Controllers/Api/AdmissionIntakeController.cs'), /AutoValidateAntiforgeryToken/);
});
