const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');

test('student import execution is an authorized atomic bounded workflow', () => {
    const api = read('EduOS.App/Controllers/Api/StudentImportsController.cs');
    const service = read('EduOS.Service/Services/Students/StudentImportExecutionService.cs');
    assert.match(api, /\[Authorize\(Roles = "TenantAdmin"\)\]/);
    assert.match(api, /\[RequireModule\("STUDENT"\)\]/);
    assert.match(api, /\[AutoValidateAntiforgeryToken\]/);
    assert.match(api, /\[HttpPost\("execute"\)\]/);
    assert.match(api, /ExecuteSliceAsync/);
    assert.ok(api.includes('[HttpPost("errors")]'));
    assert.match(api, /PreviewAllErrorsAsync/);
    assert.match(api, /SafeCsvCell/);
    assert.match(api, /job-status/);
    assert.match(api, /pending-corrections/);
    assert.match(api, /ExportPendingCorrectionsAsync/);
    const job = read('EduOS.Service/Services/Students/StudentImportExecutionService.JobStatus.cs');
    assert.match(job, /GetJobStatusAsync/);
    assert.match(job, /x\.TenantId == tenant/);
    assert.match(job, /ids\.Contains\(x\.RequestId\)/);
    assert.match(service, /BuildCsvSlice/);
    assert.match(service, /sourceRowOffset/);
    assert.match(api, /\[HttpGet\("\{reference:guid\}"\)\]/);
    assert.match(service, /IsolationLevel\.Serializable/);
    assert.match(service, /MaxBatchRows = 100/);
    assert.match(service, /SourceScope = "StudentImportSource"/);
    // Execution preflight must not turn a deadlock/EF failure into a normal
    // response that causes the surrounding transaction to attempt CommitAsync.
    assert.match(service, /_preview\\.PreviewForExecutionAsync/);
    assert.match(service, /check\\.StatusCode >= 500/);
    const preview = read('EduOS.Service/Services/Students/StudentImportPreviewService.cs');
    const previewContract = read('EduOS.Core/Interfaces/IServices/IStudentImportPreviewService.cs');
    assert.match(previewContract, /PreviewForExecutionAsync/);
    assert.match(preview, /propagateInfrastructureErrors: true/);
    assert.match(preview, /catch \\(Exception\\) when \\(propagateInfrastructureErrors\\)/);
    assert.match(service, /new StudentPersonLink/);
    assert.match(service, /new StudentEnrollment/);
    assert.match(service, /new ImportLogItem/);
    assert.match(service, /new IdempotencyRecord/);
    assert.doesNotMatch(service, /IgnoreQueryFilters\(/);
});

