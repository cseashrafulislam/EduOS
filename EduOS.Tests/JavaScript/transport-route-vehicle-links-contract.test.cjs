'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'../..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const base='EduOS.App/wwwroot/js/transport-operations/';
const names=['core','catalog','campuses','choices','create','render','close','list'];
const scripts=names.map(x=>read(base+'route-vehicle-'+x+'.js'));
scripts.forEach(x=>new Function(x));
const all=scripts.join('\n');
assert.match(all,/RequestVerificationToken/);
assert.match(all,/clientRequestId/);
assert.match(all,/routeRowVersion/);
assert.match(all,/vehicleRowVersion/);
assert.match(all,/effectiveTo/);
assert.match(all,/textContent/);
assert.doesNotMatch(all,/innerHTML/);
const partial=read('EduOS.App/Views/TransportOperations/_RouteVehicleLinks.cshtml');
assert.match(partial,/transportRouteVehicleForm/);
assert.match(partial,/AntiForgeryToken/);
const view=read('EduOS.App/Views/TransportOperations/Index.cshtml');
names.forEach(x=>assert.ok(view.includes('route-vehicle-'+x+'.js')));
console.log('Transport route-vehicle UI contracts: PASS');
